#!/usr/bin/env python3
"""Validate wiki/detections.yaml and regenerate the wiki catalog pages.

Usage:
    python scripts/build_wiki.py            # validate + write
    python scripts/build_wiki.py --check    # validate + fail if pages are stale

The YAML is a flat `- id:` record list with `key: value` lines (same subset as
Sneaky²'s wiki generator). No third-party dependency.
"""

from __future__ import annotations

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "wiki", "detections.yaml")
DETECTIONS = os.path.join(ROOT, "wiki", "DETECTIONS.md")
CHEATSHEET = os.path.join(ROOT, "wiki", "CHEATSHEET.md")
PACKAGED_CATALOG = os.path.join(ROOT, "PufferRelay", "catalog_data.yaml")

REQUIRED = [
    "id", "class", "handler", "mode", "when", "detects", "proves", "limits",
    "fields", "output", "severity", "next", "status",
]
CLASSES = [
    "inventory", "credentials", "hashes", "kerberos", "ad", "network", "web",
    "files", "weakness", "cloud", "ai", "active",
]
MODES = {"passive", "active"}
SEVERITIES = {"critical", "high", "medium", "low", "varies"}
STATUSES = {"implemented", "partial", "planned"}
EXTRA_HANDLERS = {"quickwins", "live", "proxy", "commands", "serveme"}

GENERATED_HEADER = (
    "<!-- generated by scripts/build_wiki.py from wiki/detections.yaml; "
    "do not edit by hand -->"
)


def parse(path):
    entries, current = [], None
    with open(path, encoding="utf-8") as handle:
        for raw in handle:
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            if line.startswith("- "):
                if current:
                    entries.append(current)
                current = {}
                line = line[2:].strip()
            if current is None or ":" not in line:
                continue
            key, value = line.split(":", 1)
            value = value.strip()
            if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
                value = value[1:-1]
            current[key.strip()] = value
    if current:
        entries.append(current)
    return entries


def known_handlers():
    try:
        sys.path.insert(0, ROOT)
        from PufferRelay.pcap_processing.pcap_parser import HANDLERS

        return set(HANDLERS)
    except Exception as error:  # keep --check usable in a bare checkout
        print(f"warning: cannot import HANDLERS ({error}); skipping coverage", file=sys.stderr)
        return set()


def validate(entries):
    errors = []
    ids = set()
    seen_handlers = set()
    for index, entry in enumerate(entries):
        label = entry.get("id", f"#{index}")
        for field in REQUIRED:
            if not entry.get(field):
                errors.append(f"{label}: missing field {field!r}")
        if entry.get("id") in ids:
            errors.append(f"{label}: duplicate id")
        ids.add(entry.get("id"))
        if entry.get("class") not in CLASSES:
            errors.append(f"{label}: class must be one of {', '.join(CLASSES)}")
        if entry.get("mode") not in MODES:
            errors.append(f"{label}: mode must be passive or active")
        if entry.get("severity") not in SEVERITIES:
            errors.append(f"{label}: severity must be critical/high/medium/low/varies")
        if entry.get("status") not in STATUSES:
            errors.append(f"{label}: status must be implemented/partial/planned")
        handler = entry.get("handler", "")
        if handler in seen_handlers:
            errors.append(f"{label}: handler {handler!r} has more than one entry")
        seen_handlers.add(handler)
        if entry.get("mode") == "active" and handler not in {
            "live", "proxy", "commands", "serveme"
        }:
            errors.append(f"{label}: active entry has unknown mode handler {handler!r}")
        if entry.get("mode") == "passive" and handler in {
            "live", "proxy", "commands", "serveme"
        }:
            errors.append(f"{label}: active handler {handler!r} must use mode: active")

    handlers = known_handlers()
    if handlers:
        missing = sorted(handlers - seen_handlers)
        unknown = sorted(
            handler for handler in seen_handlers
            if handler and handler not in handlers | EXTRA_HANDLERS
        )
        for handler in missing:
            errors.append(f"handler {handler!r} has no detection entry")
        for handler in unknown:
            errors.append(f"handler {handler!r} is not in the registry")
    return errors


def render_detections(entries):
    lines = [
        GENERATED_HEADER,
        "# Detections",
        "",
        "The catalog of everything PufferRelay extracts, what it proves, what it "
        "cannot prove, and where the output lands. Generated from "
        "`detections.yaml`; see `intake.md` before adding an entry.",
        "",
        "> Detection is not exploitation. A passive finding says what crossed the "
        "wire; verify before acting, and respect the scope.",
        "",
        f"{len(entries)} entries: {sum(1 for e in entries if e['mode'] == 'passive')} "
        f"passive, {sum(1 for e in entries if e['mode'] == 'active')} active.",
        "",
    ]
    for name in CLASSES:
        rows = [entry for entry in entries if entry["class"] == name]
        if not rows:
            continue
        title = name.capitalize()
        lines.append(f"## {title} ({len(rows)})")
        lines.append("")
        lines.append("| When | Handler | Detects | Severity | Status |")
        lines.append("|---|---|---|---|---|")
        for entry in rows:
            lines.append(
                f"| {entry['when']} | `{entry['handler']}` | {entry['detects']} | "
                f"{entry['severity']} | {entry['status']} |"
            )
        lines.append("")
        for entry in rows:
            lines.append(f"### `{entry['handler']}` — {entry['id']}")
            lines.append("")
            lines.append(f"**Mode:** {entry['mode']}  ")
            lines.append(f"**Proves:** {entry['proves']}  ")
            lines.append(f"**Limits:** {entry['limits']}  ")
            lines.append(f"**Output:** {entry['output']}  ")
            lines.append(f"**Next:** {entry['next']}  ")
            if entry.get("fields") and entry["fields"] != "n/a":
                lines.append(f"**Capture fields:** {entry['fields']}  ")
            if entry.get("references"):
                lines.append(f"**Reference:** {entry['references']}")
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_cheatsheet(entries):
    lines = [
        GENERATED_HEADER,
        "# Cheatsheet",
        "",
        "One-page recall card: given what the capture shows, which handler to run "
        "and what it gets you. Start here; the full reasoning is in "
        "[DETECTIONS.md](DETECTIONS.md) and [decision-guide.md](decision-guide.md).",
        "",
        "> Passive analysis only. ACTIVE commands are suggestions; confirm scope.",
        "",
        "## Common runs",
        "",
        "```bash",
        "pufferrelay -f capture.pcapng --dump out            # everything + agent feed",
        "pufferrelay -f capture.pcapng --credentials-only    # identities/secrets only",
        "pufferrelay -f capture.pcapng --only kerberos,kerberoast,asrepcatcher",
        "pufferrelay -q capture.pcapng --dump out            # add protocol-level weaknesses",
        "pufferrelay -r --has-creds --json                   # ask the database",
        "```",
        "",
        "## Passive detections",
        "",
        "| Capture looks like | `--only` handler | You get | Watch out |",
        "|---|---|---|---|",
    ]
    for entry in entries:
        if entry["mode"] != "passive":
            continue
        lines.append(
            f"| {entry['when']} | `{entry['handler']}` | {entry['output']} | "
            f"{entry['limits']} |"
        )
    lines.extend([
        "",
        "## Active modes (opt-in, warned, authorized)",
        "",
        "| Need | Mode | Guard rail |",
        "|---|---|---|",
    ])
    for entry in entries:
        if entry["mode"] != "active":
            continue
        lines.append(
            f"| {entry['when']} | `--{entry['handler']}` | {entry['limits']} |"
        )
    lines.extend([
        "",
        "## Triage order",
        "",
        "1. `services` + `ips` + `dns` — know the battlefield.",
        "2. `httptokens`, `ldap`, `http`, `ftp`, `smtp`, `imap`, `pop3`, `snmp`,",
        "   `dbcreds` — reusable secrets first.",
        "3. `kerberos`, `kerberoast`, `ntlm`, `asrepcatcher` — offline-crackable material.",
        "4. `relays`, `coercion`, `adcs`, `sccm`, `ipv6`, `smb` — attack paths.",
        "5. `files`, `smbobjects` — content that decides the engagement.",
        "",
    ])
    return "\n".join(lines).rstrip() + "\n"


def write_or_check(path, content, check):
    if check:
        try:
            with open(path, encoding="utf-8") as handle:
                current = handle.read()
        except OSError:
            return [f"{path}: missing (run scripts/build_wiki.py)"]
        if current.replace("\r\n", "\n") != content:
            return [f"{path}: stale (run scripts/build_wiki.py)"]
        return []
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(content)
    print(f"wrote {os.path.relpath(path, ROOT)}")
    return []


def main(argv=None):
    check = "--check" in (argv or sys.argv[1:])
    entries = parse(SRC)
    errors = validate(entries)
    if errors:
        for error in errors:
            print(f"ERROR: {error}", file=sys.stderr)
        return 1

    errors = []
    errors += write_or_check(DETECTIONS, render_detections(entries), check)
    errors += write_or_check(CHEATSHEET, render_cheatsheet(entries), check)
    # The installed CLI needs the catalog; ship a copy inside the package.
    with open(SRC, encoding="utf-8") as handle:
        source_text = handle.read()
    errors += write_or_check(PACKAGED_CATALOG, source_text, check)
    if errors:
        for error in errors:
            print(f"ERROR: {error}", file=sys.stderr)
        return 1
    print(f"ok: {len(entries)} detection entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
