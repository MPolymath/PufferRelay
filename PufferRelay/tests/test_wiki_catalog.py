"""The wiki catalog stays valid, complete and generated (no hand edits)."""

import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CATALOG = os.path.join(ROOT, "wiki", "detections.yaml")


def test_catalog_check_passes():
    result = subprocess.run(
        [sys.executable, "scripts/build_wiki.py", "--check"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=120,
    )
    assert result.returncode == 0, result.stderr


def test_every_registered_handler_has_an_entry():
    from PufferRelay.pcap_processing.pcap_parser import HANDLERS

    with open(CATALOG, encoding="utf-8") as handle:
        catalog = handle.read()
    for handler in HANDLERS:
        assert f"handler: {handler}\n" in catalog, handler


def test_generated_pages_are_present_and_generated():
    for name in ("DETECTIONS.md", "CHEATSHEET.md"):
        with open(os.path.join(ROOT, "wiki", name), encoding="utf-8") as handle:
            content = handle.read()
        assert "generated by scripts/build_wiki.py" in content, name
        assert "Limits:" in content or "Watch out" in content, name
